CREATE TABLE customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name varchar(200) NOT NULL CHECK (
    btrim(full_name) <> ''
    AND full_name !~ '[[:cntrl:]]'
  ),
  email varchar(320) NOT NULL UNIQUE CHECK (
    btrim(email) <> ''
    AND email = lower(email)
    AND email ~ (
      '^[A-Za-z0-9.!#$%&''*+/=?^_`{|}~-]+@'
      || '[A-Za-z0-9][A-Za-z0-9.-]*\.[A-Za-z]{2,}$'
    )
  ),
  phone varchar(50) CHECK (
    phone IS NULL
    OR (
      btrim(phone) <> ''
      AND phone ~ '^[+()0-9 -]+$'
      AND length(regexp_replace(phone, '[^0-9]', '', 'g')) BETWEEN 5 AND 15
      AND (
        position('+' in phone) = 0
        OR (
          position('+' in phone) = 1
          AND phone !~ '.+\+'
        )
      )
    )
  ),
  active boolean NOT NULL DEFAULT true,
  registered_at timestamp NOT NULL
);

CREATE TABLE products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku varchar(64) NOT NULL UNIQUE CHECK (sku ~ '^[A-Z0-9][A-Z0-9._-]{0,63}$'),
  name varchar(300) NOT NULL CHECK (
    btrim(name) <> ''
    AND name !~ '[[:cntrl:]]'
  ),
  price numeric(12, 2) NOT NULL CHECK (price > 0),
  stock_quantity integer NOT NULL CHECK (stock_quantity BETWEEN 0 AND 1000000),
  active boolean NOT NULL DEFAULT true
);

CREATE TABLE customer_orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES customers (id) ON DELETE RESTRICT,
  status varchar(20) NOT NULL DEFAULT 'NEW' CHECK (
    status IN (
      'NEW',
      'PAID',
      'SHIPPED',
      'DELIVERED',
      'CANCELLED'
    )
  ),
  created_at timestamp NOT NULL,
  paid_at timestamp,
  shipped_at timestamp,
  delivered_at timestamp,
  cancelled_at timestamp,
  note varchar(500) CHECK (
    note IS NULL
    OR (
      btrim(note) <> ''
      AND note !~ '[[:cntrl:]]'
    )
  ),
  CONSTRAINT chk_order_timestamps CHECK (
    (
      status = 'NEW'
      AND paid_at IS NULL
      AND shipped_at IS NULL
      AND delivered_at IS NULL
      AND cancelled_at IS NULL
    )
    OR (
      status = 'PAID'
      AND paid_at IS NOT NULL
      AND shipped_at IS NULL
      AND delivered_at IS NULL
      AND cancelled_at IS NULL
    )
    OR (
      status = 'SHIPPED'
      AND paid_at IS NOT NULL
      AND shipped_at IS NOT NULL
      AND delivered_at IS NULL
      AND cancelled_at IS NULL
    )
    OR (
      status = 'DELIVERED'
      AND paid_at IS NOT NULL
      AND shipped_at IS NOT NULL
      AND delivered_at IS NOT NULL
      AND cancelled_at IS NULL
    )
    OR (
      status = 'CANCELLED'
      AND cancelled_at IS NOT NULL
      AND shipped_at IS NULL
      AND delivered_at IS NULL
      AND (
        paid_at IS NULL
        OR cancelled_at >= paid_at
      )
    )
  ),
  CONSTRAINT chk_order_timestamp_order CHECK (
    (
      paid_at IS NULL
      OR paid_at >= created_at
    )
    AND (
      shipped_at IS NULL
      OR shipped_at >= paid_at
    )
    AND (
      delivered_at IS NULL
      OR delivered_at >= shipped_at
    )
    AND (
      cancelled_at IS NULL
      OR cancelled_at >= created_at
    )
  )
);

CREATE TABLE order_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES customer_orders (id) ON DELETE CASCADE,
  product_id bigint NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
  quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
  unit_price numeric(12, 2) NOT NULL CHECK (unit_price > 0),
  UNIQUE (order_id, product_id)
);

CREATE INDEX idx_orders_customer_id ON customer_orders (customer_id);

CREATE INDEX idx_orders_status ON customer_orders (status);

CREATE INDEX idx_orders_created_at ON customer_orders (created_at);

CREATE INDEX idx_items_product_id ON order_items (product_id);
