CREATE TABLE readers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    library_card_number varchar(50) NOT NULL UNIQUE,
    full_name varchar(200) NOT NULL CHECK (btrim(full_name) <> ''),
    email varchar(320) NOT NULL UNIQUE CHECK (btrim(email) <> ''),
    active boolean NOT NULL DEFAULT true,
    registered_at date NOT NULL
);

CREATE TABLE books (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn varchar(32) NOT NULL UNIQUE CHECK (btrim(isbn) <> ''),
    title varchar(300) NOT NULL CHECK (btrim(title) <> ''),
    author varchar(200) NOT NULL CHECK (btrim(author) <> ''),
    publication_year integer NOT NULL CHECK (publication_year > 0),
    total_copies integer NOT NULL CHECK (total_copies >= 1),
    available_copies integer NOT NULL CHECK (
        available_copies >= 0 AND available_copies <= total_copies
    )
);

CREATE TABLE book_issue_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reader_id bigint NOT NULL REFERENCES readers(id) ON DELETE RESTRICT,
    book_id bigint NOT NULL REFERENCES books(id) ON DELETE RESTRICT,
    status varchar(20) NOT NULL DEFAULT 'CREATED'
        CHECK (status IN ('CREATED','APPROVED','ISSUED','RETURNED','REJECTED','CANCELLED')),
    requested_at timestamp NOT NULL,
    issued_on date,
    due_on date,
    returned_on date,
    note varchar(500),
    CONSTRAINT chk_request_issue_dates CHECK (
        (status IN ('CREATED', 'APPROVED', 'REJECTED', 'CANCELLED')
            AND issued_on IS NULL AND due_on IS NULL AND returned_on IS NULL)
        OR (status = 'ISSUED'
            AND issued_on IS NOT NULL AND due_on IS NOT NULL AND returned_on IS NULL)
        OR (status = 'RETURNED'
            AND issued_on IS NOT NULL AND due_on IS NOT NULL AND returned_on IS NOT NULL)
    ),
    CONSTRAINT chk_request_due_date CHECK (
        due_on IS NULL OR due_on = issued_on + 30
    ),
    CONSTRAINT chk_request_return_date CHECK (
        returned_on IS NULL OR returned_on >= issued_on
    )
);

CREATE UNIQUE INDEX uq_active_reader_book_request
    ON book_issue_requests(reader_id, book_id)
    WHERE status IN ('CREATED', 'APPROVED', 'ISSUED');

CREATE INDEX idx_requests_reader_id ON book_issue_requests(reader_id);
CREATE INDEX idx_requests_book_id ON book_issue_requests(book_id);
CREATE INDEX idx_requests_status ON book_issue_requests(status);
CREATE INDEX idx_requests_requested_at ON book_issue_requests(requested_at);
